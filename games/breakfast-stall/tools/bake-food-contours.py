"""Bake radial contour samples and sprite cells from the food atlas.

Run from the repository root with Python 3 and ImageMagick on PATH.
"""
import json
import math
from pathlib import Path
import subprocess

PROJECT = Path(__file__).resolve().parents[1]
ATLAS = PROJECT / "assets/resources/breakfast-art/food-icons.png"
OUTPUT = PROJECT / "assets/breakfast/runtime/food-contours.ts"
KINDS = ("soyMilk", "bun", "teaEgg", "riceCake", "corn", "flowerRoll", "oilStick", "sweetPotato")
COLUMNS = 3
THRESHOLD = 128
SAMPLES = 144

width, height = map(int, subprocess.check_output(
    ["magick", str(ATLAS), "-format", "%w %h", "info:"], text=True
).split())
rgba = subprocess.check_output(["magick", str(ATLAS), "-alpha", "on", "-depth", "8", "rgba:-"])
assert len(rgba) == width * height * 4 and width % COLUMNS == 0
cell = width // COLUMNS
assert height % cell == 0 and len(KINDS) <= COLUMNS * height // cell


def outline(index):
    left, top = index % COLUMNS * cell, index // COLUMNS * cell

    def alpha(x, y):
        ix, iy = round(x), round(y)
        if ix < 0 or iy < 0 or ix >= cell or iy >= cell:
            return 0
        return rgba[((top + iy) * width + left + ix) * 4 + 3]

    solid = [(x, y) for y in range(cell) for x in range(cell) if alpha(x, y) >= THRESHOLD]
    assert solid, f"Empty atlas cell for {KINDS[index]}"
    cx = sum(x for x, _ in solid) / len(solid)
    cy = sum(y for _, y in solid) / len(solid)
    assert alpha(cx, cy) >= THRESHOLD
    points = []
    for step in range(SAMPLES):
        angle = step * 2 * math.pi / SAMPLES
        dx, dy = math.cos(angle), -math.sin(angle)
        radius = math.hypot(cell, cell)
        while alpha(cx + dx * radius, cy + dy * radius) < THRESHOLD:
            radius -= .25
        points.append([round(cx + dx * (radius + .22), 2), round(cy + dy * (radius + .22), 2)])
    return {"cell": [left, top], "center": [round(cx, 2), round(cy, 2)], "edge": points}


lines = [
    "// Generated by cocos-game/tools/bake-food-contours.py from breakfast-art/food-icons.png.",
    'import type { FoodKind } from "../core/types";',
    "",
    "type Pixel = readonly [number, number];",
    "export interface FoodContour {",
    "    readonly cell: Pixel;",
    "    readonly center: Pixel;",
    "    readonly edge: readonly Pixel[];",
    "}",
    "",
    f"export const FOOD_ATLAS_SIZE = [{width}, {height}] as const;",
    f"export const FOOD_ATLAS_CELL_SIZE = {cell};",
    "export const FOOD_CONTOURS: Record<FoodKind, FoodContour> = {",
]
for index, kind in enumerate(KINDS):
    profile = outline(index)
    lines.append(f'    {kind}: {{ cell: {profile["cell"]}, center: {profile["center"]}, edge: [')
    for start in range(0, SAMPLES, 8):
        batch = json.dumps(profile["edge"][start:start + 8])[1:-1]
        lines.append(f"        {batch},")
    lines.append("    ] },")
lines.extend(["};", ""])
content = "\n".join(lines)
if not OUTPUT.exists() or OUTPUT.read_text() != content:
    OUTPUT.write_text(content)
